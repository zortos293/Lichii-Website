\set ON_ERROR_STOP on
\getenv owner_password LICHII_OWNER_PASSWORD
\getenv app_password LICHII_APP_PASSWORD

SELECT 'CREATE ROLE lichii' WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'lichii') \gexec
SELECT 'CREATE ROLE lichii_unkey' WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'lichii_unkey') \gexec
ALTER ROLE lichii LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT NOREPLICATION NOBYPASSRLS PASSWORD :'owner_password';
ALTER ROLE lichii_unkey LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS CONNECTION LIMIT 32 PASSWORD :'app_password';

SELECT 'CREATE DATABASE lichii OWNER lichii' WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'lichii') \gexec
REVOKE ALL ON DATABASE lichii FROM PUBLIC;
GRANT CONNECT ON DATABASE lichii TO lichii_unkey;

\connect lichii
GRANT USAGE ON SCHEMA public TO lichii_unkey;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO lichii_unkey;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO lichii_unkey;
ALTER DEFAULT PRIVILEGES FOR ROLE lichii IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO lichii_unkey;
ALTER DEFAULT PRIVILEGES FOR ROLE lichii IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO lichii_unkey;
